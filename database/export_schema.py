"""Export the application's schema constants without importing or running it."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = PROJECT_ROOT / "database" / "schema.sql"
SOURCES = (("app.py", "SCHEMA"), ("app.py", "FAVORITES_SCHEMA"),
           ("attachments.py", "ATTACHMENTS_SCHEMA"))


def schema_constant(source: Path, name: str) -> str:
    """Read only a top-level literal; never execute application module code."""
    module = ast.parse(source.read_text(encoding="utf-8"), filename=str(source))
    for statement in module.body:
        if isinstance(statement, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name
            for target in statement.targets
        ):
            value = ast.literal_eval(statement.value)
            if isinstance(value, str):
                return value.strip()
            break
    raise ValueError(f"{source.name}: {name} 必须是顶层 SQL 字符串常量。")


def render_schema(project_root: Path = PROJECT_ROOT) -> str:
    parts = [
        "-- Generated by python database/export_schema.py; do not edit by hand.",
        "-- Schema only: no accounts, notices, favorites or attachment records.",
        "PRAGMA foreign_keys = ON;",
    ]
    for filename, name in SOURCES:
        parts.append(f"-- Source: {filename}:{name}\n" + schema_constant(project_root / filename, name))
    return "\n\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="从源代码导出空数据库结构，不读取或创建运行数据库。")
    parser.add_argument("--check", action="store_true", help="只检查 schema.sql 是否与源代码一致")
    args = parser.parse_args()
    expected = render_schema()
    if args.check:
        if not SCHEMA_PATH.is_file() or SCHEMA_PATH.read_text(encoding="utf-8") != expected:
            print("schema.sql 与源代码不一致，请运行 python database/export_schema.py 后提交更新。")
            return 1
        print("schema.sql 与应用源代码一致。")
        return 0
    SCHEMA_PATH.write_text(expected, encoding="utf-8")
    print("已生成 database/schema.sql（仅表结构，不含数据）。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
